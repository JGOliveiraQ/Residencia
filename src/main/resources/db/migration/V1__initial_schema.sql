CREATE TABLE categories (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(120) NOT NULL,
    normalized_name VARCHAR(120) NOT NULL UNIQUE,
    description VARCHAR(500),
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP NOT NULL
);
CREATE TABLE suppliers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    corporate_name VARCHAR(180) NOT NULL,
    trade_name VARCHAR(180),
    cnpj VARCHAR(14) NOT NULL UNIQUE,
    phone VARCHAR(30),
    email VARCHAR(180),
    address VARCHAR(255),
    city VARCHAR(120),
    state VARCHAR(2),
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP NOT NULL
);
CREATE TABLE products (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sku VARCHAR(60) NOT NULL UNIQUE,
    name VARCHAR(180) NOT NULL,
    description VARCHAR(500),
    brand VARCHAR(120),
    unit VARCHAR(20) NOT NULL,
    cost_price DECIMAL(19,4) NOT NULL DEFAULT 0,
    sale_price DECIMAL(19,4) NOT NULL DEFAULT 0,
    current_stock DECIMAL(19,4) NOT NULL DEFAULT 0,
    minimum_stock DECIMAL(19,4) NOT NULL DEFAULT 0,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    category_id BIGINT NOT NULL,
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP NOT NULL,
    CONSTRAINT fk_product_category FOREIGN KEY (category_id) REFERENCES categories(id)
);
CREATE INDEX idx_products_name ON products(name);
CREATE INDEX idx_products_category ON products(category_id);
CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(150) NOT NULL,
    email VARCHAR(180) NOT NULL UNIQUE,
    password VARCHAR(255) NOT NULL,
    role VARCHAR(20) NOT NULL,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP NOT NULL
);
CREATE TABLE stock_movements (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type VARCHAR(20) NOT NULL,
    description VARCHAR(500),
    reason VARCHAR(100),
    supplier_id BIGINT,
    user_id BIGINT NOT NULL,
    created_at TIMESTAMP NOT NULL,
    CONSTRAINT fk_movement_supplier FOREIGN KEY (supplier_id) REFERENCES suppliers(id),
    CONSTRAINT fk_movement_user FOREIGN KEY (user_id) REFERENCES users(id)
);
CREATE TABLE stock_movement_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    movement_id BIGINT NOT NULL,
    product_id BIGINT NOT NULL,
    quantity DECIMAL(19,4) NOT NULL,
    adjustment_direction VARCHAR(20),
    previous_stock DECIMAL(19,4) NOT NULL,
    resulting_stock DECIMAL(19,4) NOT NULL,
    unit_cost DECIMAL(19,4),
    created_at TIMESTAMP NOT NULL,
    CONSTRAINT fk_item_movement FOREIGN KEY (movement_id) REFERENCES stock_movements(id),
    CONSTRAINT fk_item_product FOREIGN KEY (product_id) REFERENCES products(id)
);
CREATE INDEX idx_movements_created_at ON stock_movements(created_at);
CREATE INDEX idx_items_product ON stock_movement_items(product_id);
